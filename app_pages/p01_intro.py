st.header("ثانيًا: ماذا يعني «تعلّم» بالضبط؟ — تجربة عملية")

st.markdown(
    "عندنا بيانات: كل نقطة زرقاء هي مثال واحد (مثلًا: عدد سنوات الخبرة ← الراتب). "
    "«التعلّم» = البحث عن الخط الذي يمرّ أقرب ما يمكن إلى كل النقاط. "
    "جرّب أن تحرّك المؤشّرين بنفسك وراقب رقم **الخطأ** أسفلهما."
)

x, y = toy_regression(n=50, noise=3.0)

cs1, cs2 = st.columns([1, 2], gap="medium")
with cs1:
    w = st.slider("الميل  w  (slope)", -1.0, 5.0, 1.0, 0.1,
                  help="كم يزيد التنبؤ عند زيادة x بوحدة واحدة")
    b = st.slider("الثابت  b  (intercept)", -10.0, 20.0, 0.0, 0.5,
                  help="قيمة التنبؤ عندما x = 0")
    pred = w * x + b
    mse = float(np.mean((y - pred) ** 2))
    best_w, best_b = np.polyfit(x, y, 1)
    best_mse = float(np.mean((y - (best_w * x + best_b)) ** 2))

    st.metric("الخطأ الحالي  MSE", f"{mse:,.2f}",
              delta=f"{mse - best_mse:+,.2f} عن الأفضل", delta_color="inverse")
    st.caption(f"أفضل خط ممكن رياضيًا: w = {best_w:.2f} ، b = {best_b:.2f}")
    if mse < best_mse * 1.05:
        st.success("ممتاز! وصلت تقريبًا إلى أفضل خط ممكن.", icon=":material/check_circle:")

with cs2:
    fig = go.Figure()
    for xi, yi, pi in zip(x, y, pred):
        fig.add_trace(go.Scatter(x=[xi, xi], y=[yi, pi], mode="lines",
                                 line=dict(color="#E9A0AC", width=1.4),
                                 showlegend=False, hoverinfo="skip"))
    fig.add_trace(go.Scatter(x=x, y=y, mode="markers", name="البيانات الحقيقية",
                             marker=dict(size=9, color=PALETTE["indigo"],
                                         line=dict(width=1, color="white"))))
    xs = np.linspace(x.min(), x.max(), 50)
    fig.add_trace(go.Scatter(x=xs, y=w * xs + b, mode="lines", name="خطّك (الموديل)",
                             line=dict(color=PALETTE["orange"], width=3.5)))
    fig.add_trace(go.Scatter(x=xs, y=best_w * xs + best_b, mode="lines",
                             name="الخط الأفضل", line=dict(color=PALETTE["teal"],
                                                           width=2, dash="dash")))
    style_fig(fig, height=430, xaxis_title="x — المتغيّر المستقل (Feature)",
              yaxis_title="y — الهدف (Target)")
    st.plotly_chart(fig, width="stretch")

