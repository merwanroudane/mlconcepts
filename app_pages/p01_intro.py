st.markdown("كل ما سنفعله في هذه المنصة يُختزل في هذه الجملة الرياضية:")
eq(r"y \;=\; f(X) \;+\; \varepsilon",
   "y = الهدف،  X = المتغيّرات،  f = العلاقة الحقيقية المجهولة،  ε = الضوضاء العشوائية")

st.markdown("ولأن `f` مجهولة إلى الأبد، فنحن نبني تقديرًا لها نسمّيه `f̂` (إف هات):")
eq(r"\hat{y} \;=\; \hat{f}(X)",
   "ŷ (y hat) = التنبؤ،  f̂ = الموديل الذي تعلّمناه من البيانات")

st.markdown(
    "ومهمّتنا كلها هي جعل `f̂` قريبة من `f` بأقصى ما تسمح به البيانات. "
    f"العنصر {en('ε')} مهمّ جدًا: هو الجزء العشوائي الذي **لا يمكن** التنبؤ به أبدًا "
    "(مزاج البائع، ظرف خاص، خطأ قياس). وجوده يعني أن الدقة 100% مستحيلة، "
    "وأن من يدّعي خطأً = صفر على بيانات حقيقية فهو إمّا مخطئ أو يُخفي مشكلة "
    f"({en('data leakage')} — سنراها في صفحة البيانات).",
)

